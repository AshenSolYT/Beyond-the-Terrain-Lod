package com.anonymous.beyondthehorizon.config;

import com.anonymous.beyondthehorizon.BeyondTheHorizonConstants;
import net.minecraft.util.Mth;

/**
 * Settings of the tile generator. On a dedicated server this file is edited by the server admin, in singleplayer it belongs to the player.
 */
public class ServerConfig {
    private static final String FILE = BeyondTheHorizonConstants.CONFIG_NAME + "-server.json";

    public boolean enabled = true;
    /** Farthest distance from a player, in blocks, for which tiles are generated. */
    public int maxDistance = BeyondTheHorizonConstants.MAX_LOD_DISTANCE;
    /** Finest LOD level clients may request. 0 means one sample per block. */
    public int minLevel = 0;
    /** 0 picks a value based on the CPU core count. */
    public int generatorThreads = 0;
    public int maxQueuedRequestsPerPlayer = 512;
    public int maxInFlightPerPlayer = 6;
    /**
     * Tiles in flight per generator thread: tiles handed to the threads but not yet reported back. Finished tiles are reported on the
     * server thread, and when that is late the threads would sit idle with nothing left to do, so a few more than one tile per thread
     * wait in line. The tiles in line cannot be reordered any more, so too many makes the threads work on tiles the player has left behind.
     */
    public int inFlightPerThread = 6;
    /**
     * Java priority of the generator threads, 1 (lowest) to 9. At 1 they are starved while the game itself, chunk generation and mods
     * like C2ME keep all cores busy; they still pause for late frames at any priority, see WorkThrottle.
     */
    public int generatorPriority = Thread.NORM_PRIORITY - 1;
    /** Generator threads while distant terrain is pre-generated by /farplane pregen distant; 0 is all cores but one. */
    public int pregenThreads = 0;
    /** The distant structure layer: villages and other structures above ground as rough boxes, apart from the terrain. */
    public boolean structuresEnabled = true;
    /** How far from a player, in blocks, structures are sent. */
    public int structureDistance = 3072;
    public boolean diskCache = true;
    public int memoryCacheTiles = 2048;
    /** Detailed tiles built from real chunks around players. */
    public boolean detailEnabled = true;
    public int detailMaxRadiusChunks = BeyondTheHorizonConstants.MAX_DETAIL_RADIUS_CHUNKS;
    /** Read chunks saved on disk for detailed tiles. Without it only chunks loaded in memory show real blocks. */
    public boolean detailReadSavedChunks = true;
    /**
     * Chunks nobody has visited yet are generated in memory for detailed tiles, with trees and structures, and kept in the world
     * folder. Nothing is added to the world itself. Players can turn it off for themselves; this switch turns it off for everyone.
     */
    public boolean detailGenerateUnexplored = true;
    /** Threads for detailed tiles, separate from the generator threads. 0 picks a value based on the CPU core count. */
    public int detailThreads = 0;
    /**
     * How many blocks down from the top of a column detailed tiles look, in the End and everywhere else. In singleplayer the owner of
     * the world sets it in the detailed terrain settings instead. Changing it makes the chunks generated in memory again.
     */
    public int detailScanDepth = BeyondTheHorizonConstants.DEFAULT_SCAN_DEPTH;
    /**
     * Ore veins in the overworld chunks generated in memory. Off they are made faster and with much less garbage; the veins lie deep
     * and only show now and then in the walls of caves and cliffs. In singleplayer the owner of the world sets it in the detailed
     * terrain settings instead.
     */
    public boolean detailOreVeins = false;
    public int detailScanDepthEnd = BeyondTheHorizonConstants.DEFAULT_END_SCAN_DEPTH;

    public void sanitize() {
        this.maxDistance = Mth.clamp(this.maxDistance, BeyondTheHorizonConstants.MIN_LOD_DISTANCE, BeyondTheHorizonConstants.MAX_LOD_DISTANCE);
        this.minLevel = Mth.clamp(this.minLevel, 0, BeyondTheHorizonConstants.MAX_MIN_LEVEL);
        this.generatorThreads = Mth.clamp(this.generatorThreads, 0, 16);
        this.detailThreads = Mth.clamp(this.detailThreads, 0, 8);
        this.maxQueuedRequestsPerPlayer = Mth.clamp(this.maxQueuedRequestsPerPlayer, 16, 4096);
        this.maxInFlightPerPlayer = Mth.clamp(this.maxInFlightPerPlayer, 1, 64);
        this.inFlightPerThread = Mth.clamp(this.inFlightPerThread, 1, 16);
        this.generatorPriority = Mth.clamp(this.generatorPriority, Thread.MIN_PRIORITY, Thread.MAX_PRIORITY - 1);
        this.pregenThreads = Mth.clamp(this.pregenThreads, 0, 64);
        this.structureDistance = Mth.clamp(this.structureDistance, 512, 16384);
        this.memoryCacheTiles = Mth.clamp(this.memoryCacheTiles, 0, 65536);
        this.detailMaxRadiusChunks = Mth.clamp(this.detailMaxRadiusChunks, 0, BeyondTheHorizonConstants.MAX_DETAIL_RADIUS_CHUNKS);
        this.detailScanDepth = scanDepth(this.detailScanDepth);
        this.detailScanDepthEnd = scanDepth(this.detailScanDepthEnd);
    }

    /** A scan depth within the limits, rounded to a whole step. */
    public static int scanDepth(int depth) {
        int step = BeyondTheHorizonConstants.SCAN_DEPTH_STEP;
        return Mth.clamp((depth + step / 2) / step * step, BeyondTheHorizonConstants.MIN_SCAN_DEPTH, BeyondTheHorizonConstants.MAX_SCAN_DEPTH);
    }

    public int resolvedThreads() {
        if (this.generatorThreads > 0) {
            return this.generatorThreads;
        }
        int cores = Runtime.getRuntime().availableProcessors();
        // Phones heat up and slow down under constant load on all cores. The generator threads run at the lowest priority and make
        // room for late frames (see WorkThrottle), so on computers they may have all cores but one, and at least two: with cores
        // minus 3 a 4-core computer had a single thread, and filling the horizon took minutes.
        return BeyondTheHorizonConstants.ANDROID ? 1 : Mth.clamp(cores - 1, 2, 8);
    }

    /**
     * How many tiles a player may have in flight: the setting, or at least {@link #inFlightPerThread} per generator thread, so that the threads do not
     * wait for the next request to come from the client.
     */
    public int inFlightLimit() {
        return Math.max(this.maxInFlightPerPlayer, this.resolvedThreads() * this.inFlightPerThread);
    }

    public int resolvedDetailThreads() {
        if (this.detailThreads > 0) {
            return this.detailThreads;
        }
        // Detailed tiles run above the distant terrain generator in priority, so more of them only take its share of the CPU. All of
        // them only work while loading is urgent (a player flying fast), see resolvedCalmDetailThreads.
        int cores = Runtime.getRuntime().availableProcessors();
        return BeyondTheHorizonConstants.ANDROID ? Mth.clamp(cores / 2, 1, 4) : Mth.clamp(cores * 3 / 8, 1, 4);
    }

    /**
     * Detailed tiles worked on at the same time while loading is not urgent (walking around). On phones one, so frames stay smooth on
     * their few cores; on computers all of them, since the threads make room for late frames anyway (see WorkThrottle) and holding
     * them back only left cores idle.
     */
    public int resolvedCalmDetailThreads() {
        int all = this.resolvedDetailThreads();
        return BeyondTheHorizonConstants.ANDROID ? 1 : all;
    }

    /** A copy to change in the settings screen without touching what the running server reads. */
    public ServerConfig copy() {
        return ConfigFiles.copy(this, ServerConfig.class);
    }

    /**
     * Takes over the settings the running server reads again on every request. The thread counts, the priority and the caches are set up
     * when the world is opened, so changes to those wait for the next start (see {@link #needsRestart}).
     */
    public void applyLive(ServerConfig other) {
        this.enabled = other.enabled;
        this.maxDistance = other.maxDistance;
        this.minLevel = other.minLevel;
        this.maxQueuedRequestsPerPlayer = other.maxQueuedRequestsPerPlayer;
        this.maxInFlightPerPlayer = other.maxInFlightPerPlayer;
        this.inFlightPerThread = other.inFlightPerThread;
        this.pregenThreads = other.pregenThreads;
        this.structuresEnabled = other.structuresEnabled;
        this.structureDistance = other.structureDistance;
        this.detailEnabled = other.detailEnabled;
        this.detailMaxRadiusChunks = other.detailMaxRadiusChunks;
        this.detailReadSavedChunks = other.detailReadSavedChunks;
        this.detailGenerateUnexplored = other.detailGenerateUnexplored;
        this.detailScanDepth = other.detailScanDepth;
        this.detailOreVeins = other.detailOreVeins;
        this.detailScanDepthEnd = other.detailScanDepthEnd;
    }

    /** Whether a setting that is only read when the world is opened differs between the two. */
    public boolean needsRestart(ServerConfig other) {
        return this.generatorThreads != other.generatorThreads
            || this.generatorPriority != other.generatorPriority
            || this.detailThreads != other.detailThreads
            || this.diskCache != other.diskCache
            || this.memoryCacheTiles != other.memoryCacheTiles;
    }

    public void save() {
        ConfigFiles.save(FILE, this);
    }

    public static ServerConfig load() {
        ConfigFiles.migrate("beyond-the-horizon-server.json", FILE);
        ServerConfig config = ConfigFiles.load(FILE, BeyondTheHorizonConstants.MOD_ID + "-server.json", ServerConfig.class, ServerConfig::new);
        config.sanitize();
        return config;
    }
}
